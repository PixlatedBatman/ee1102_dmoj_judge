"""Judge-side files for function-style problems ("write a function f(...) that returns ...").

Each test input is a JSON list of arguments. The grader wraps the student's code with a harness that
calls the function once and prints repr() of the return value; the checker compares that with the
reference solution's repr(). The student's code still runs in the judge's normal sandbox.
"""

# Line 1 of the submitted program: stash stdin, and swallow anything the student prints.
HEADER = ("import sys as _ee_sys, io as _ee_io; _ee_stdin = _ee_sys.stdin.read(); "
          "_ee_sys.stdin = _ee_io.StringIO(''); _ee_stdout = _ee_sys.stdout; _ee_sys.stdout = _ee_io.StringIO()\n")

FOOTER = '''

def _ee_run():
    import copy, json
    fn = globals().get({function!r})
    if not callable(fn):
        _ee_stdout.write('__EE_NO_FUNCTION__\\n')
        return
    args = json.loads(_ee_stdin)
    before = copy.deepcopy(args)
    result = fn(*args)
    if args != before:
        _ee_stdout.write('__EE_INPUT_MODIFIED__\\n')
    elif {must_be_new!r} and any(result is a for a in args):
        _ee_stdout.write('__EE_NOT_NEW__\\n')
    else:
        _ee_stdout.write(repr(result) + '\\n')
    _ee_stdout.flush()


_ee_run()
'''

GRADER = '''# Generated by ee1102_problemset: wraps the submission in the function-call harness.
from dmoj.executors import executors
from dmoj.graders.standard import StandardGrader

HEADER = {header!r}
FOOTER = {footer!r}


class Grader(StandardGrader):
    def _generate_binary(self):
        source = HEADER.encode() + self.source + FOOTER.encode()
        return executors[self.language].Executor(
            self.problem.id, source,
            hints=self.problem.config.hints or [], unbuffered=self.problem.config.unbuffered,
        )
'''

# Feedback strings are stored in a 50-char DB column, so keep them short. Extended feedback (shown under
# "Judge feedback" on the submission page) is only given for the visible example cases.
CHECKER = '''# Generated by ee1102_problemset: exact compare of repr() output, with hints for common mistakes.
from dmoj.result import CheckerResult
from dmoj.utils.unicode import utf8text

VISIBLE = {visible!r}  # the first VISIBLE cases are the statement's examples

MESSAGES = {{
    '__EE_NO_FUNCTION__': {no_function!r},
    '__EE_INPUT_MODIFIED__': 'your function changed its input',
    '__EE_NOT_NEW__': 'return a new list, not the input list',
}}


def _clip(text, limit=1000):
    return text if len(text) <= limit else text[:limit] + ' ...'


def check(process_output, judge_output, point_value=1, case_position=None, **kwargs):
    got, expected = utf8text(process_output).strip(), utf8text(judge_output).strip()
    if got == expected:
        return CheckerResult(True, point_value)
    if got in MESSAGES:
        feedback = MESSAGES[got]
    elif got == 'None':
        feedback = 'returned None: print instead of return?'
    else:
        feedback = None
    extended = None
    if case_position is not None and case_position < VISIBLE:
        shown = f'({{MESSAGES[got]}})' if got in MESSAGES else got
        extended = (f'Example {{case_position + 1}} from the problem statement.\\n'
                    f'Your function returned:\\n  {{_clip(shown)}}\\nExpected:\\n  {{_clip(expected)}}')
    return CheckerResult(False, 0, feedback, extended)
'''


def grader_source(function, must_be_new=False):
    return GRADER.format(header=HEADER, footer=FOOTER.format(function=function, must_be_new=must_be_new))


def checker_source(function, visible=0):
    return CHECKER.format(no_function=f'no function named {function}'[:50], visible=visible)
